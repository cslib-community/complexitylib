#!/usr/bin/env python3
"""Check whether a restacked pull request still makes exactly the change that was approved.

Usage: python3 scripts/check_restack.py APPROVED NEW [--base REF] [--approved-base REF]

A restack (merging `main` into a branch, or rebasing it) gives the PR a new head, and approvals
name heads. This script replays the approved change, from its base to APPROVED, onto the `main`
commit that NEW is based on, using `git merge-tree`. That replay is what the merge
queue would build from the approved head on that `main`. NEW passes when its tree equals the replay
exactly: every path, mode and byte. The only exceptions are the `mk_all` aggregates (`AGGREGATES`).
Their merges can order lines differently, so they pass when they contain the same lines in any
order; CI's `lake exe mk_all --check` rejects any order but the canonical one. A replay conflict on any other file,
and any other difference, is reported, so moving, reordering or editing the PR's lines during a
conflict resolution never passes.

Bases: NEW is based on its merge base with `--base` (default `origin/main`; run `git fetch origin`
first, since a stale ref only produces a false "differs"). APPROVED is based on its merge base
with `--approved-base`, or with `--base` when that is not given. For any PR approved while it was
based on another branch (a stacked PR), pass that branch's head at approval time as
`--approved-base`. Otherwise the replayed change includes the lower branch's changes, which were
not reviewed in this PR, and they would carry the approval if the lower PR never landed.

The replay uses the attributes in the new head's base commit (`--attr-source`) and no others: it
ignores `core.attributesFile` and the system file, and refuses to run when `info/attributes` sets
anything. It pins the merge settings, including the rename limit. It runs the tracked `bibkeys`
driver of `references.bib` as this checkout's `scripts/resolve_bib_conflict.py`, makes every other
configured merge driver report a conflict, and refuses a configured driver that would shadow a
built-in one (`text`, `binary`, `union`). History is read without replace refs, grafts or the
commit-graph file, `GIT_TEST_*` variables are dropped, and a shallow repository is refused.
Local Git configuration and history-rewriting state therefore cannot change the result. The script
still trusts the object store and the refs it is given, so the non-author who queues reruns it in
their own clone after `git fetch origin`. Run it from a checkout of current `origin/main`, not of
the PR, since the replay runs this checkout's code. A `references.bib` merge written by
`scripts/resolve_bib_conflict.py`, with nothing else changed, passes.

Exit status: 0 when NEW is the replayed approved change; 1 when it differs (the differing paths
and diffs are printed); 2 on a usage or Git error, including an approved change that is empty
relative to its base. A missing commit is fetched from `origin` by its hash. Requires Git 2.42 or
later.

A pass does not replace CI: the replay combines the approved change with newer `main`, which the
merge queue tests in any case. The carry-forward rule is in AGENTS.md ("Restacks").
"""

from __future__ import annotations

import argparse
import os
import re
import shlex
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Root import aggregators generated by `lake exe mk_all`, whose `--check` in CI pins their content.
AGGREGATES = ("Complexity.lean", "ComplexityResults.lean", "abstracts/ComplexityAbstracts.lean")
# At most this many diff lines are printed per differing path.
MAX_DIFF_LINES = 60
# Fixed merge settings, so the replay does not depend on the caller's Git configuration.
MERGE_CONFIG = ("-c", "merge.conflictStyle=merge", "-c", "merge.renames=true",
                "-c", "merge.directoryRenames=conflict", "-c", "merge.renormalize=false",
                "-c", "merge.default=text", "-c", "merge.renameLimit=7000")
# Built-in drivers; a configured driver with one of these names would replace it.
BUILTIN_DRIVERS = frozenset({"text", "binary", "union"})
# Removed from the environment: `GIT_CONFIG` redirects only `git config`, so it would hide
# configured drivers from `driver_config` while `merge-tree` still ran them.
# `GIT_TEST_*` variables are dropped too: `GIT_TEST_COMMIT_GRAPH`, for one, loads the commit-graph
# file whatever `core.commitGraph` says.
UNSET_VARIABLES = ("GIT_ATTR_SOURCE", "GIT_CONFIG", "GIT_SHALLOW_FILE")
# The driver that `.gitattributes` names for `references.bib`, and this checkout's implementation.
BIB_DRIVER = "bibkeys"
BIB_RESOLVER = ROOT / "scripts" / "resolve_bib_conflict.py"
CONFLICT_MARKER = re.compile(rb"^(<{7}|={7}|>{7})( |$)")


class GitError(Exception):
    pass


def environment() -> dict[str, str]:
    """The caller's environment without system attributes, replace refs or grafts."""
    env = {key: value for key, value in os.environ.items()
           if key not in UNSET_VARIABLES and not key.startswith("GIT_TEST_")}
    env.update(GIT_ATTR_NOSYSTEM="1", GIT_NO_REPLACE_OBJECTS="1", GIT_GRAFT_FILE=os.devnull)
    return env


def git(root: Path, *args: str, ok: tuple[int, ...] = (0,)) -> subprocess.CompletedProcess[bytes]:
    # The commit-graph file is a cache of parents that a local edit could falsify.
    result = subprocess.run(["git", "-c", "core.commitGraph=false", "-C", str(root), *args],
                            capture_output=True, env=environment())
    if result.returncode not in ok:
        message = result.stderr.decode("utf-8", "replace").strip()
        raise GitError(f"git {' '.join(args)}: {message}")
    return result


def out(root: Path, *args: str) -> str:
    return git(root, *args).stdout.decode().strip()


def resolve(root: Path, ref: str) -> str:
    """The commit `ref` names, fetching it from `origin` by hash when it is missing locally."""
    try:
        return out(root, "rev-parse", "--verify", "--quiet", "--end-of-options", f"{ref}^{{commit}}")
    except GitError:
        if not re.fullmatch(r"[0-9a-f]{7,40}", ref):
            raise GitError(f"unknown revision `{ref}`") from None
    try:
        git(root, "fetch", "--no-tags", "--quiet", "origin", ref)
    except GitError as error:
        raise GitError(f"`{ref}` is not available locally and could not be fetched: {error}")
    return out(root, "rev-parse", "--verify", "--end-of-options", f"{ref}^{{commit}}")


def merge_base(root: Path, base: str, head: str) -> str:
    try:
        return out(root, "merge-base", base, head)
    except GitError:
        raise GitError(f"`{head}` has no merge base with `{base}`") from None


def tree(root: Path, commit: str) -> str:
    return out(root, "rev-parse", f"{commit}^{{tree}}")


def check_local_attributes(root: Path) -> None:
    """Refuse when the repository's own `info/attributes`, which Git cannot disable, sets anything."""
    path = Path(out(root, "rev-parse", "--path-format=absolute", "--git-path", "info/attributes"))
    if path.is_file() and any(line.strip() and not line.lstrip().startswith("#")
                              for line in path.read_text(errors="replace").splitlines()):
        raise GitError(f"{path} sets attributes, which could change the replay; "
                       "move them aside or run the check in another clone")


def driver_config(root: Path) -> list[str]:
    """`-c` options pinning every merge driver the replay could run: `bibkeys` runs this checkout's
    resolver, and every other configured driver reports a conflict without merging."""
    listed = git(root, "config", "--null", "--name-only", "--get-regexp",
                 r"^merge\..*\.driver$", ok=(0, 1))
    names = {key[len("merge."):-len(".driver")]
             for key in listed.stdout.decode("utf-8", "surrogateescape").split("\0") if key}
    names.discard(BIB_DRIVER)
    if names & BUILTIN_DRIVERS:
        raise GitError(f"configured merge drivers {', '.join(sorted(names & BUILTIN_DRIVERS))} "
                       "would replace Git's built-in ones; run the check in another clone")
    if any("=" in name or "\n" in name for name in names):
        raise GitError("a configured merge driver name contains `=` or a newline, so the replay "
                       "cannot disable it; run the check in another clone")
    # Git expands `%` in a driver command, so a literal `%` in a path is doubled.
    python, script = (shlex.quote(str(p)).replace("%", "%%") for p in (sys.executable, BIB_RESOLVER))
    resolver = f"{python} {script} --driver %O %A %B"
    options = ["-c", f"merge.{BIB_DRIVER}.driver={resolver}"]
    for name in sorted(names):
        options += ["-c", f"merge.{name}.driver=exit 1"]
    return options


def replay(root: Path, approved_base: str, approved: str, onto: str) -> tuple[str, set[str]]:
    """The tree of `approved_base..approved` merged onto `onto`, and the paths that conflicted."""
    check_local_attributes(root)
    result = git(root, f"--attr-source={onto}", "-c", f"core.attributesFile={os.devnull}",
                 *MERGE_CONFIG, *driver_config(root), "merge-tree", "--write-tree", "--name-only",
                 "-z", "--no-messages", f"--merge-base={approved_base}", onto, approved, ok=(0, 1))
    fields = result.stdout.split(b"\0")
    if not re.fullmatch(rb"[0-9a-f]{40,64}", fields[0]):
        raise GitError("unexpected `git merge-tree` output; Git 2.42 or later is required")
    conflicts = {f.decode("utf-8", "surrogateescape") for f in fields[1:] if f}
    return fields[0].decode(), conflicts


def changed_paths(root: Path, left: str, right: str) -> list[str]:
    raw = git(root, "diff-tree", "-r", "--name-only", "-z", "--no-renames",
              "--ignore-submodules=none", left, right)
    return [p.decode("utf-8", "surrogateescape") for p in raw.stdout.split(b"\0") if p]


def blob_lines(root: Path, treeish: str, path: str) -> list[bytes] | None:
    result = git(root, "cat-file", "blob", f"{treeish}:{path}", ok=(0, 128))
    return result.stdout.split(b"\n") if result.returncode == 0 else None


def same_lines(root: Path, replayed: str, new: str, path: str) -> bool:
    """Whether `path` holds the same lines in both trees, in any order, ignoring conflict markers."""
    left, right = blob_lines(root, replayed, path), blob_lines(root, new, path)
    if left is None or right is None:
        return left is right
    left = [line for line in left if not CONFLICT_MARKER.match(line)]
    return Counter(line for line in left if line) == Counter(line for line in right if line)


def show(root: Path, replayed: str, new: str, path: str) -> list[str]:
    diff = git(root, "diff", "--no-ext-diff", "--no-textconv", "--no-color", "--no-renames",
               "--src-prefix=replayed/", "--dst-prefix=new/", replayed, new, "--", path)
    lines = diff.stdout.decode("utf-8", "replace").split("\n")
    shown = ["  " + line.replace("\r", "\\r") for line in lines[:MAX_DIFF_LINES] if line]
    if len(lines) > MAX_DIFF_LINES:
        shown.append(f"  ... {len(lines) - MAX_DIFF_LINES} more lines")
    return shown


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("approved", help="the approved head commit")
    parser.add_argument("new", help="the new head")
    parser.add_argument("--base", default="origin/main",
                        help="the branch both heads target (default origin/main)")
    parser.add_argument("--approved-base",
                        help="base of the approved head, e.g. a lower PR's head (stacked PRs)")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root
    try:
        approved = resolve(root, args.approved)
        new = resolve(root, args.new)
        base = resolve(root, args.base)
        approved_ref = resolve(root, args.approved_base) if args.approved_base else base
        if out(root, "rev-parse", "--is-shallow-repository") == "true":
            raise GitError("the repository is shallow, so merge bases may be wrong; "
                           "run `git fetch --unshallow origin` first")
        approved_base = merge_base(root, approved_ref, approved)
        new_base = merge_base(root, base, new)
        if tree(root, approved_base) == tree(root, approved):
            raise GitError(f"the approved head {approved[:12]} makes no change relative to "
                           f"{approved_base[:12]}; check --approved-base")
        replayed, conflicts = replay(root, approved_base, approved, new_base)
        new_tree = tree(root, new)
        differing = [] if replayed == new_tree else changed_paths(root, replayed, new_tree)
        if replayed != new_tree and not differing:
            raise GitError("the trees differ but no differing path was found")
    except GitError as error:
        print(f"check_restack: {error}", file=sys.stderr)
        return 2
    heads = (f"approved {approved[:12]} (from {approved_base[:12]}) replayed onto "
             f"{new_base[:12]}, new {new[:12]}")
    # A conflicted path needs review even when the new head matches the replay's tentative content
    # (as when it keeps a file that `main` deleted), unless it is an aggregate with the same lines.
    # Identical trees pass only without conflicts.
    suspect = sorted(set(differing) | conflicts)
    accepted = [p for p in suspect if p in AGGREGATES and same_lines(root, replayed, new, p)]
    rejected = [p for p in suspect if p not in accepted]
    if not rejected:
        note = (f"; aggregates differing only in line order: {', '.join(accepted)}"
                if accepted else "")
        print(f"Restack check: identical to the approved change: {heads}{note}. "
              f"Command: python3 scripts/check_restack.py {approved} {new}"
              + (f" --approved-base {args.approved_base}" if args.approved_base else "")
              + (f" --base {args.base}" if args.base != "origin/main" else ""))
        return 0
    print(f"Restack check: differs from the approved change: {heads}.")
    for path in rejected:
        reason = ("the replay conflicted here; review how it was resolved" if path in conflicts
                  else "the new head differs from the replayed approved change")
        print(f"{path!r}: {reason}" if not path.isprintable() else f"{path}: {reason}")
        print("\n".join(show(root, replayed, new, path)))
    return 1


if __name__ == "__main__":
    sys.exit(main())
