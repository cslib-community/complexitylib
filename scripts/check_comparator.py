#!/usr/bin/env python3
"""Compare selected library proofs to independently stated contracts with all bundled kernels.

The generated challenge holes are deliberate comparator inputs, never library proofs.
The runner always uses the official sandbox and never substitutes an unsandboxed check.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "comparator" / "ComplexityComparatorChallenges"
AXIOMS = ["propext", "Quot.sound", "Classical.choice"]
HEADER = "-- Generated by scripts/check_comparator.py; do not edit.\n"

# The statement definitions, theorem names and allowed axioms are fixed inputs, not solution output.
SUITES = {
    "basic": (
        "Basic",
        [
            ("manyOneTrans", "ManyOneTrans.{u, v, w}"),
            ("nonprojectionNeedsGate", "NonprojectionNeedsGate.{u, s}"),
        ],
    ),
    "automation": (
        "Automation",
        [("padded_function", "PaddedFunction"), ("dot_product_halves", "DotProductHalves")],
    ),
    "sat": ("SAT", [("exact_count", "ExactCount"), ("not_eth", "NotETH")]),
}


def write_generated(path: Path, contents: str, *, lean: bool = False) -> None:
    """Do not follow symlinks or replace a hand-written Lean source."""
    if path.is_symlink():
        raise ValueError(f"refusing to overwrite symlink: {path}")
    if lean and path.exists() and not path.read_text().startswith(HEADER):
        raise ValueError(f"refusing to overwrite an unrecognized source: {path}")
    path.write_text(contents)


def prepare(suite: str) -> Path:
    """Put trusted challenge source outside the sandbox's writable .lake directory."""
    if GENERATED.resolve() != GENERATED:
        raise ValueError(f"generated source directory must not contain symlinks: {GENERATED}")
    GENERATED.mkdir(parents=True, exist_ok=True)
    name, theorems = SUITES[suite]
    namespace = f"ComplexityComparator.{name}"
    challenge = f"ComplexityComparatorChallenges.{name}"
    source = HEADER + f"""module

public import {namespace}.Statements

public section

universe u v w s

"""
    for theorem, statement in theorems:
        source += f"theorem {namespace}.{theorem} : {namespace}.{statement} := by\n  sorry\n\n"
    write_generated(GENERATED / f"{name}.lean", source, lean=True)
    config = {
        "challenge_module": challenge,
        "solution_module": f"{namespace}.Solution",
        "theorem_names": [f"{namespace}.{theorem}" for theorem, _ in theorems],
        "permitted_axioms": AXIOMS,
    }
    path = GENERATED / f"{suite}.json"
    write_generated(path, json.dumps(config, indent=2) + "\n")
    return path


def negative_control() -> int:
    """A valid proof of True must be rejected as a proof of the basic contracts."""
    config = json.loads(prepare("basic").read_text())
    module = "ComplexityComparatorChallenges.WrongStatement"
    source = HEADER + "module\n\npublic section\n\n"
    for theorem in config["theorem_names"]:
        source += f"theorem {theorem} : True := True.intro\n\n"
    write_generated(GENERATED / "WrongStatement.lean", source, lean=True)
    config["solution_module"] = module
    path = GENERATED / "negative.json"
    write_generated(path, json.dumps(config, indent=2) + "\n")
    print("Checking that valid proofs of changed statements are rejected", flush=True)
    result = subprocess.run(
        ["lake", "comparator", "--paranoid", f"--config={path}"], cwd=ROOT,
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    )
    print(result.stdout, end="", flush=True)
    expected = (
        "Challenge and solution theorem statement do not match: "
        "'ComplexityComparator.Basic.manyOneTrans'"
    )
    if result.returncode == 1 and expected in result.stdout:
        print("Negative control passed: the changed theorem statement was rejected.")
        return 0
    print("Negative control failed: expected a theorem-statement mismatch.", file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "suites", nargs="*", metavar="{basic,automation,sat}",
        help="suites to compare (default: basic automation; SAT is opt-in)",
    )
    parser.add_argument(
        "--prepare-only", action="store_true",
        help="write challenge sources and configurations for inspection, without checking proofs",
    )
    parser.add_argument(
        "--negative-control", action="store_true",
        help="also require valid proofs of True to fail comparison with the basic statements",
    )
    args = parser.parse_args()
    suites = args.suites or ["basic", "automation"]
    for suite in suites:
        if suite not in SUITES:
            parser.error(f"unknown suite {suite!r}; choose from {', '.join(SUITES)}")
    if args.prepare_only and args.negative_control:
        parser.error("--prepare-only and --negative-control cannot be combined")
    try:
        for suite in dict.fromkeys(suites):
            config = prepare(suite)
            if args.prepare_only:
                print(f"Prepared {suite}: {config.relative_to(ROOT)}; no proof check was run.")
                continue
            print(f"Checking {suite} with lake comparator --paranoid", flush=True)
            result = subprocess.run(
                ["lake", "comparator", "--paranoid", f"--config={config}"], cwd=ROOT,
            )
            if result.returncode:
                print(
                    f"Comparator did not accept {suite} (exit {result.returncode}). "
                    "The command may have rejected the proofs or been unable to run; "
                    "see its diagnostics above. No sandbox bypass was attempted.",
                    file=sys.stderr,
                )
                return result.returncode if result.returncode > 0 else 128 - result.returncode
        if args.negative_control:
            return negative_control()
    except (OSError, ValueError) as error:
        print(f"Comparator could not run: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
